async def save_phone(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if context.user_data.get("bosqich") != "telefon":
        return

    phone = update.message.text.strip()

    if not phone.replace("+", "").isdigit() or len(phone.replace("+", "")) < 9:
        await update.message.reply_text(
            "❌ Telefon noto‘g‘ri!\nMasalan: +998901234567"
        )
        return

    yonalish = context.user_data["yonalish"]
    sana = context.user_data["sana"]
    vaqt = context.user_data["vaqt"]
    yolovchilar = context.user_data["yo‘lovchilar"]

    conn = sqlite3.connect("taxi_baza.db")
    cursor = conn.cursor()

    # Shu safardagi band joylarni hisoblaymiz
    cursor.execute("""
        SELECT COALESCE(SUM(yolovchilar), 0)
        FROM buyurtmalar
        WHERE yonalish = ?
          AND sana = ?
          AND vaqt = ?
          AND holat != 'Bekor qilindi'
    """, (yonalish, sana, vaqt))

    band_joy = cursor.fetchone()[0]
    bosh_joy = MASHINA_SIGIMI - band_joy

    # Joy yetmasa, buyurtmani saqlamaymiz
    if yolovchilar > bosh_joy:
        conn.close()
        await update.message.reply_text(
            f"❌ Afsuski, bu safarda faqat {bosh_joy} ta bo‘sh joy bor.\n"
            "Yo‘lovchilar sonini kamaytiring yoki boshqa vaqtni tanlang."
        )
        return

    telegram_id = update.effective_user.id

    cursor.execute("""
        INSERT INTO buyurtmalar
        (yonalish, sana, vaqt, yolovchilar,
         erkaklar, ayollar, telefon, yolovchi_telegram_id)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
    """, (
        yonalish,
        sana,
        vaqt,
        yolovchilar,
        context.user_data["erkaklar"],
        context.user_data["ayollar"],
        phone,
        telegram_id
    ))

    order_id = cursor.lastrowid

    cursor.execute("""
        SELECT ism, telefon, telegram_id
        FROM haydovchilar
    """)
    drivers = cursor.fetchall()

    conn.commit()
    conn.close()

    # Yangi bo‘sh joylar soni
    yangi_bosh_joy = bosh_joy - yolovchilar

    context.user_data["bosqich"] = "yakunlandi"

    info = (
        f"🚕 YANGI TAXI BUYURTMASI №{order_id}\n\n"
        f"🛣 Yo‘nalish: {yonalish}\n"
        f"📅 Sana: {sana}\n"
        f"🕒 Vaqt: {vaqt}\n"
        f"👥 Yo‘lovchilar: {yolovchilar}\n"
        f"👨 Erkaklar: {context.user_data['erkaklar']}\n"
        f"👩 Ayollar: {context.user_data['ayollar']}\n"
        f"📱 Telefon: {phone}\n"
        f"💺 Bo‘sh joy: {yangi_bosh_joy} ta\n"
        "📌 Holat: Yangi"
    )

    driver_name = drivers[0][0] if drivers else "Hozircha yo‘q"
    driver_phone = drivers[0][1] if drivers else "Hozircha yo‘q"

    await update.message.reply_text(
        "✅ Buyurtmangiz qabul qilindi!\n\n"
        f"🚕 Buyurtma №{order_id}\n"
        "🚗 Chevrolet Cobalt\n"
        "🔢 60 L 899 FB\n"
        f"👨‍✈️ Haydovchi: {driver_name}\n"
        f"📞 Telefon: {driver_phone}\n\n"
        f"💺 Jami joy: {MASHINA_SIGIMI} ta\n"
        f"👥 Band joy: {MASHINA_SIGIMI - yangi_bosh_joy} ta\n"
        f"✅ Bo‘sh joy: {yangi_bosh_joy} ta"
    )

    await context.bot.send_message(
        chat_id=ADMIN_ID,
        text=info
    )

    keyboard = InlineKeyboardMarkup([
        [InlineKeyboardButton(
            "✅ Buyurtmani olish",
            callback_data=f"accept_{order_id}"
        )]
    ])

    for driver in drivers:
        try:
            await context.bot.send_message(
                chat_id=driver[2],
                text=info + "\n\n🚕 Yangi buyurtma!",
                reply_markup=keyboard
            )
        except Exception as e:
            print("Haydovchiga yuborishda xatolik:", e)

    await reset_passenger_menu(update, context)


