def bosh_joylarni_hisobla(yonalish, sana, vaqt):
    conn = sqlite3.connect("taxi_baza.db")
    cursor = conn.cursor()

    cursor.execute("""
        SELECT COALESCE(SUM(yolovchilar), 0)
        FROM buyurtmalar
        WHERE yonalish = ?
          AND sana = ?
          AND vaqt = ?
          AND holat != 'Bekor qilindi'
    """, (yonalish, sana, vaqt))

    band_joy = cursor.fetchone()[0]
    conn.close()

    bosh_joy = MASHINA_SIGIMI - band_joy

    return max(0, bosh_joy)


