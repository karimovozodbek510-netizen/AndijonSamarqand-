async def driver_panel(update: Update, context: ContextTypes.DEFAULT_TYPE):
    driver_id = update.effective_user.id
    choice = update.message.text.strip()

    conn = sqlite3.connect("taxi_baza.db")
    cursor = conn.cursor()

    cursor.execute(
        "SELECT ism FROM haydovchilar WHERE telegram_id = ?",
        (driver_id,)
    )
    driver = cursor.fetchone()

    if not driver:
        conn.close()
        return

    name = driver[0]

    if choice == "📋 Mening buyurtmalarim":
        cursor.execute("""
            SELECT id, yonalish, sana, vaqt, yolovchilar, holat
            FROM buyurtmalar
            WHERE haydovchi_ismi = ?
            ORDER BY id DESC
        """, (name,))

        orders = cursor.fetchall()
        conn.close()

        if not orders:
            await update.message.reply_text("📭 Sizda hali buyurtmalar yo‘q.")
            return

        for order in orders:
            buttons = []

            if order[5] == "Haydovchi oldi":
                buttons.append([
                    InlineKeyboardButton(
                        "❌ Buyurtmani bekor qilish",
                        callback_data=f"driver_cancel_{order[0]}"
                    )
                ])
                buttons.append([
                    InlineKeyboardButton(
                        "✅ Safarni tugatish",
                        callback_data=f"finish_trip_{order[0]}"
                    )
                ])

            keyboard = InlineKeyboardMarkup(buttons) if buttons else None

            await update.message.reply_text(
                f"🚕 BUYURTMA №{order[0]}\n\n"
                f"🛣 Yo‘nalish: {order[1]}\n"
                f"📅 Sana: {order[2]}\n"
                f"🕒 Vaqt: {order[3]}\n"
                f"👥 Yo‘lovchilar: {order[4]}\n"
                f"📌 Holat: {order[5]}",
                reply_markup=keyboard
            )

    elif choice == "🚕 Yangi buyurtmalar":
        cursor.execute("""
            SELECT id, yonalish, sana, vaqt, yolovchilar, telefon
            FROM buyurtmalar
            WHERE holat = 'Yangi'
            ORDER BY id DESC
        """)
        orders = cursor.fetchall()
        conn.close()

        if not orders:
            await update.message.reply_text("📭 Yangi buyurtmalar yo‘q.")
            return

        for order in orders:
            keyboard = InlineKeyboardMarkup([
                [InlineKeyboardButton(
                    "✅ Buyurtmani olish",
                    callback_data=f"accept_{order[0]}"
                )]
            ])

            await update.message.reply_text(
                f"🚕 BUYURTMA №{order[0]}\n\n"
                f"🛣 Yo‘nalish: {order[1]}\n"
                f"📅 Sana: {order[2]}\n"
                f"🕒 Vaqt: {order[3]}\n"
                f"👥 Yo‘lovchilar: {order[4]}\n"
                f"📱 Telefon: {order[5]}",
                reply_markup=keyboard
            )

    elif choice == "📊 Safarlarim statistikasi":
        cursor.execute("""
            SELECT COUNT(*), COALESCE(SUM(yolovchilar), 0)
            FROM buyurtmalar
            WHERE haydovchi_ismi = ?
        """, (name,))
        total_orders, total_passengers = cursor.fetchone()
        conn.close()

        await update.message.reply_text(
            "📊 SIZNING STATISTIKANGIZ\n\n"
            f"🚕 Buyurtmalar: {total_orders}\n"
            f"👥 Jami yo‘lovchilar: {total_passengers}"
        )


async def driver_finish_trip(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    order_id = int(query.data.replace("finish_trip_", ""))
    driver_id = query.from_user.id

    conn = sqlite3.connect("taxi_baza.db")
    cursor = conn.cursor()

    cursor.execute(
        "SELECT ism FROM haydovchilar WHERE telegram_id = ?",
        (driver_id,)
    )
    driver = cursor.fetchone()

    if not driver:
        conn.close()
        await query.message.reply_text("❌ Siz haydovchi emassiz!")
        return

    name = driver[0]

    cursor.execute("""
        SELECT yonalish, sana, vaqt, holat
        FROM buyurtmalar
        WHERE id = ? AND haydovchi_ismi = ?
    """, (order_id, name))

    order = cursor.fetchone()

    if not order or order[3] != "Haydovchi oldi":
        conn.close()
        await query.message.reply_text(
            "❌ Bu safarni tugatib bo‘lmaydi."
        )
        return

    # Shu safardagi barcha faol buyurtmalarni tugatamiz
    cursor.execute("""
        SELECT yolovchi_telegram_id
        FROM buyurtmalar
        WHERE yonalish = ?
          AND sana = ?
          AND vaqt = ?
          AND holat NOT IN ('Bekor qilindi', 'Tugallandi')
    """, (order[0], order[1], order[2]))

    passengers = [
        row[0] for row in cursor.fetchall() if row[0]
    ]

    cursor.execute("""
        UPDATE buyurtmalar
        SET holat = 'Tugallandi',
            haydovchi_ismi = ?
        WHERE yonalish = ?
          AND sana = ?
          AND vaqt = ?
          AND holat NOT IN ('Bekor qilindi', 'Tugallandi')
    """, (name, order[0], order[1], order[2]))

    conn.commit()
    conn.close()

    await query.message.reply_text(
        "✅ SAFAR MUVAFFAQIYATLI TUGATILDI!\n\n"
        f"🛣 Yo‘nalish: {order[0]}\n"
        f"📅 Sana: {order[1]}\n"
        f"🕒 Vaqt: {order[2]}\n\n"
        "💺 Mashinadagi joylar yana bo‘shatildi."
    )

    xabar = (
        "🏁 SAFAR TUGATILDI!\n\n"
        f"🛣 Yo‘nalish: {order[0]}\n"
        f"📅 Sana: {order[1]}\n"
        f"🕒 Vaqt: {order[2]}"
    )

    await context.bot.send_message(
        chat_id=ADMIN_ID,
        text=xabar
    )

    for passenger_id in set(passengers):
        try:
            await context.bot.send_message(
                chat_id=passenger_id,
                text=xabar
            )
        except Exception as e:
            print("Yo‘lovchiga xabar yuborilmadi:", e)


