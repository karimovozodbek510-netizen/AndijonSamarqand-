async def cancel_order(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    await query.answer()

    order_id = int(query.data.split("_")[1])
    telegram_id = query.from_user.id

    conn = sqlite3.connect("taxi_baza.db")
    cursor = conn.cursor()

    cursor.execute("""
        SELECT yolovchi_telegram_id, holat, haydovchi_ismi
        FROM buyurtmalar
        WHERE id = ?
    """, (order_id,))

    order = cursor.fetchone()

    if not order:
        conn.close()
        await query.message.reply_text("❌ Buyurtma topilmadi!")
        return

    if order[0] != telegram_id:
        conn.close()
        await query.message.reply_text("❌ Bu sizning buyurtmangiz emas!")
        return

    if order[1] == "Bekor qilindi":
        conn.close()
        await query.message.reply_text("⚠️ Bu buyurtma oldin bekor qilingan!")
        return

    cursor.execute("""
        UPDATE buyurtmalar
        SET holat = 'Bekor qilindi'
        WHERE id = ?
    """, (order_id,))

    driver_name = order[2]

    driver_id = None
    if driver_name:
        cursor.execute("""
            SELECT telegram_id
            FROM haydovchilar
            WHERE ism = ?
            LIMIT 1
        """, (driver_name,))
        result = cursor.fetchone()
        if result:
            driver_id = result[0]

    conn.commit()
    conn.close()

    await query.edit_message_reply_markup(reply_markup=None)

    await query.message.reply_text(
        f"❌ {order_id}-buyurtmangiz bekor qilindi!"
    )

    # Adminga xabar
    await context.bot.send_message(
        chat_id=ADMIN_ID,
        text=f"❌ Yo‘lovchi {order_id}-buyurtmani bekor qildi."
    )

    # Buyurtmani qabul qilgan haydovchiga xabar
    if driver_id:
        await context.bot.send_message(
            chat_id=driver_id,
            text=f"❌ Yo‘lovchi {order_id}-buyurtmani bekor qildi!"
        )


app.add_handler(
    CallbackQueryHandler(cancel_order, pattern=r"^cancel_\d+$")
)

print("✅ Buyurtmani bekor qilish funksiyasi tayyor!")

